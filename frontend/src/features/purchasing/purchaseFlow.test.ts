import { describe, expect, it } from 'vitest';
import type { PurchaseOrderSummary, PurchaseRequisitionSummary } from '@/lib/api/types';
import {
  buildBoard,
  FLOW_STAGES,
  formatAutoGeneratedStockNote,
  isPoPrintable,
  isPrPrintable,
  matchesPo,
  matchesPr,
  poNextAction,
  poStage,
  prStage,
  tabCount,
  trackerStageForPr,
} from './purchaseFlow';

function pr(id: number, status: PurchaseRequisitionSummary['status']): PurchaseRequisitionSummary {
  return {
    id, doc_number: `PR-${id}`, status, reason: null, est_total: '0', items_count: 1,
    requested_by: 1, requester_name: 'Kasir Satu', is_auto_generated: false,
    submitted_at: null, created_at: '2026-10-27 00:00:00',
  };
}

function po(id: number, status: PurchaseOrderSummary['status']): PurchaseOrderSummary {
  return {
    id, doc_number: `PO-${id}`, status, receipt_status: 'none', payment_status: 'unpaid', payment_terms: 'cod',
    pr_id: 1, pr_doc_number: 'PR-1', supplier_id: 1, supplier_name: 'CV Maju', order_date: '2026-10-27',
    expected_date: null, total: '1000', created_at: '2026-10-27 00:00:00',
  };
}

describe('purchaseFlow', () => {
  it('memetakan status Permintaan ke tahap', () => {
    expect(prStage('submitted')).toBe('pr_review');
    expect(prStage('finance_checked')).toBe('po_prepare');
    expect(prStage('approved')).toBe('po_prepare');
    for (const status of ['draft', 'returned', 'rejected', 'cancelled', 'converted'] as const) {
      expect(prStage(status)).toBe('archive');
    }
  });

  it('memetakan status PO ke tahap', () => {
    for (const status of ['draft', 'pending_confirmation'] as const) expect(poStage(status)).toBe('po_prepare');
    for (const status of ['approved', 'sent', 'partially_received', 'received'] as const) expect(poStage(status)).toBe('po_send');
    expect(poStage('cancelled')).toBe('archive');
  });

  it('meringkas antrean menjadi tiga tahap dan menghitung seluruh dokumen', () => {
    const board = buildBoard(
      [pr(1, 'submitted'), pr(2, 'submitted'), pr(3, 'finance_checked'), pr(4, 'approved'), pr(5, 'rejected')],
      [po(1, 'draft'), po(2, 'pending_confirmation'), po(3, 'approved'), po(4, 'sent'), po(5, 'received'), po(6, 'cancelled')],
    );
    expect(FLOW_STAGES).toHaveLength(3);
    expect(board.pr_review.map((item) => item.id)).toEqual([1, 2]);
    expect(board.pr_ready.map((item) => item.id)).toEqual([3, 4]);
    expect(board.po_prepare.map((item) => item.id)).toEqual([1, 2]);
    expect(board.po_send.map((item) => item.id)).toEqual([3, 4, 5]);
    expect(tabCount(board, 'pr_review')).toBe(2);
    expect(tabCount(board, 'po_prepare')).toBe(4);
    expect(tabCount(board, 'po_send')).toBe(3);
    expect(tabCount(board, 'archive')).toBe(2);
  });

  it('pelacak Permintaan converted mengikuti posisi PO-nya', () => {
    const base = { status: 'converted' as const };
    expect(trackerStageForPr({ ...base, purchase_orders: [{ id: 1, doc_number: 'PO-1', status: 'draft', total: null }] })).toBe('po_prepare');
    expect(trackerStageForPr({ ...base, purchase_orders: [{ id: 1, doc_number: 'PO-1', status: 'approved', total: null }] })).toBe('po_send');
    expect(trackerStageForPr({ status: 'approved', purchase_orders: [] })).toBe('po_prepare');
  });

  it('hanya dokumen valid yang bisa dicetak', () => {
    expect(isPrPrintable('approved')).toBe(true);
    expect(isPrPrintable('converted')).toBe(true);
    expect(isPrPrintable('submitted')).toBe(false);
    expect(isPrPrintable('rejected')).toBe(false);
    expect(isPoPrintable('approved')).toBe(true);
    expect(isPoPrintable('sent')).toBe(true);
    expect(isPoPrintable('draft')).toBe(false);
    expect(isPoPrintable('pending_confirmation')).toBe(false);
    expect(isPoPrintable('cancelled')).toBe(false);
  });

  it('memformat stok dan ambang pada catatan Permintaan otomatis tanpa mengubah catatan lainnya', () => {
    expect(formatAutoGeneratedStockNote('Stok saat ini 3.000; ambang 5.000', true)).toBe('Stok saat ini 3; ambang 5');
    expect(formatAutoGeneratedStockNote('Stok saat ini 3.250; ambang 5.500', true)).toBe('Stok saat ini 3,25; ambang 5,5');
    expect(formatAutoGeneratedStockNote('Stok saat ini 3.000; ambang 5.000', false)).toBe('Stok saat ini 3.000; ambang 5.000');
    expect(formatAutoGeneratedStockNote('Permintaan tambahan', true)).toBe('Permintaan tambahan');
    expect(formatAutoGeneratedStockNote(null, true)).toBeNull();
  });

  it('label aksi PO mengikuti langkah berikutnya', () => {
    expect(poNextAction('draft')).toBe('Lanjutkan PO Draft');
    expect(poNextAction('pending_confirmation')).toBe('Lihat persetujuan Owner');
    expect(poNextAction('approved')).toBe('Cetak & konfirmasi kirim');
    expect(poNextAction('sent')).toBe('Lihat');
  });

  it('pencarian cocok pada nomor, pemohon, supplier, dan Permintaan asal', () => {
    expect(matchesPr(pr(7, 'submitted'), 'pr-7')).toBe(true);
    expect(matchesPr(pr(7, 'submitted'), 'kasir')).toBe(true);
    expect(matchesPr(pr(7, 'submitted'), 'zzz')).toBe(false);
    expect(matchesPo(po(3, 'sent'), 'maju')).toBe(true);
    expect(matchesPo(po(3, 'sent'), 'pr-1')).toBe(true);
    expect(matchesPo(po(3, 'sent'), '')).toBe(true);
  });
});
